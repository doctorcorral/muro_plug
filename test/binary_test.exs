defmodule MuroPlug.BinaryTest do
  # muro-http #24: Bytes and Slice must stay BEAM binaries in the
  # emitted step, and no HTTP body or buffer may be a list of octets.
  use ExUnit.Case, async: true

  alias MuroPlug.Step

  @source File.read!(Path.expand("../lib/muro_plug/step.ex", __DIR__))

  test "the emitted step is muro's default Elixir backend output for the pinned book" do
    assert @source =~ ~r/\A# Generated by Muro 0\.22\.36 from priv\/muro\/http\/step\.muro/
    assert @source =~ "defmodule MuroPlug.Step do"
  end

  test "slice folds match on binaries, not on list cells" do
    # sliceFold lowers to a binary match, one byte at a time.
    assert @source =~ "<<b, rest::binary>> -> recur.(recur, f.(b).(rest).(acc), rest)"
    assert @source =~ "<<>> -> acc"
    # slice / sliceAfter / sliceUntil are :binary.part and :binary.match.
    assert @source =~ ":binary.part(s, off, len)"
    assert @source =~ ":binary.match(s, <<b>>)"
    assert @source =~ "byte_size(s)"
  end

  test "the emitted step never builds or walks a list of octets" do
    forbidden = [
      ~r/:binary\.bin_to_list/,
      ~r/:erlang\.binary_to_list/,
      ~r/String\.to_charlist/,
      ~r/:erlang\.list_to_binary/,
      ~r/\[[a-z_][a-z0-9_]* \| [a-z_][a-z0-9_]*\]/,
      ~r/Enum\./,
      ~r/List\./
    ]

    for re <- forbidden, do: refute(@source =~ re, "step.ex matches #{inspect(re)}")
    # No list literal anywhere in the generated module.
    refute @source =~ "["
  end

  test "book fixtures and views are binaries" do
    for f <- [:getBuf, :postBody, :chunkBuf, :expectBuf, :twoGet, :capLine, :capHdr] do
      assert is_binary(apply(Step, f, [])), "#{f} is not a binary"
    end

    assert byte_size(Step.capLine()) > 16_384

    buf = Step.postBody()

    for v <- [:methodView, :targetView, :pathView, :queryView, :versionView] do
      assert is_binary(apply(Step, v, [buf]))
    end

    assert Step.bodyView(buf) == "abcd"
    assert is_binary(Step.headerValue(buf, 0))
  end

  test "the step refuses a list of octets" do
    list = :binary.bin_to_list(Step.getBuf())

    # The emitted slice fold only matches binaries, so a charlist
    # buffer cannot be stepped at all.
    assert {:case_clause, ^list} =
             catch_error(Step.stepFact(Step.readSt(), 2, list, 16_384, 0, 0, 0, 0, 0))
  end

  defmodule Probe do
    import Plug.Conn

    def init(o), do: o

    def call(conn, test) do
      {:ok, body, conn} = read_body(conn)
      %{adapter: {MuroPlug.Adapter, payload}} = conn

      send(test, {
        :types,
        is_binary(body),
        Enum.all?(conn.req_headers, fn {k, v} -> is_binary(k) and is_binary(v) end),
        is_binary(conn.request_path) and is_binary(conn.query_string),
        payload.body
      })

      send_resp(conn, 200, ["io", "data", ?!])
    end
  end

  test "request and response path carry binaries end to end" do
    port = MuroPlug.TestClient.serve({Probe, self()})

    r =
      MuroPlug.TestClient.request(
        port,
        "POST /p?q=1 HTTP/1.1\r\nHost: h\r\nContent-Length: 3\r\n\r\nabc"
      )

    assert_receive {:types, true, true, true, :done}
    assert r.body == "iodata!"

    r =
      MuroPlug.TestClient.request(
        port,
        "POST /p HTTP/1.1\r\nHost: h\r\nTransfer-Encoding: chunked\r\n\r\n3\r\nabc\r\n0\r\n\r\n"
      )

    assert_receive {:types, true, true, true, :done}
    assert r.status == 200
  end

  test "the adapter's buffered body is a binary view of the receive buffer" do
    req = MuroPlug.Book.step(Step.readSt(), :bytes, Step.postBody(), cfg())
    assert req.phase == 3
    assert binary_part(Step.postBody(), req.hend, req.cl) == "abcd"
  end

  defp cfg, do: %{max_body: 16_384, idle: 60_000, deadline: 0}
end
